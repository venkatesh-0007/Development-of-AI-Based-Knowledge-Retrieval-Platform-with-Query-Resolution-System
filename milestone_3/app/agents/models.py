"""Data models and schemas for Milestone 3 Multi-Agent Conversational Platform.

Covers:
- Query Understanding models (M2/M3)
- ClarificationType, ClarificationRequest & ClarificationStatus (M3.1)
- ConversationTurn & ConversationSession (M3.2)
- SpeechConfig & VoicePayload (M3.3)
- TransparencyScoreBreakdown & TransparencyPanelPayload (M3.4)
- RetrievalResult, SourceAttribution, AgentResponse & OrchestrationResult
"""
import time
import uuid
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import List, Dict, Any, Optional

class QueryType(str, Enum):
    FACTUAL = "factual"
    PROCEDURAL = "procedural"
    COMPARATIVE = "comparative"
    AMBIGUOUS = "ambiguous"
    MULTI_PART = "multi_part"

class RoutingTarget(str, Enum):
    RETRIEVAL = "retrieval"
    CLARIFICATION = "clarification"

class ConfidenceLevel(str, Enum):
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    NONE = "NONE"

class ClarificationType(str, Enum):
    AMBIGUOUS_TERM = "ambiguous_term"
    MISSING_CONTEXT = "missing_context"
    INCOMPLETE_REQUEST = "incomplete_request"
    MULTIPLE_INTERPRETATIONS = "multiple_interpretations"
    MULTI_PART_UNRESOLVED = "multi_part_unresolved"
    INSUFFICIENT_INFORMATION = "insufficient_information"

class ClarificationStatus(str, Enum):
    PENDING = "pending"
    RESOLVED = "resolved"
    CANCELLED = "cancelled"

@dataclass
class ClarificationRequest:
    """Detailed clarification proposal produced by the Clarification Agent (M3.1)."""
    original_query: str
    clarification_type: ClarificationType
    reason: str
    follow_up_question: str
    suggested_options: List[str] = field(default_factory=list)
    sub_questions: List[str] = field(default_factory=list)
    is_multi_part: bool = False
    clarification_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    status: ClarificationStatus = ClarificationStatus.PENDING
    created_at: float = field(default_factory=time.time)
    resolved_at: Optional[float] = None
    user_response: Optional[str] = None
    refined_query: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "clarification_id": self.clarification_id,
            "original_query": self.original_query,
            "clarification_type": self.clarification_type.value,
            "reason": self.reason,
            "follow_up_question": self.follow_up_question,
            "suggested_options": self.suggested_options,
            "sub_questions": self.sub_questions,
            "is_multi_part": self.is_multi_part,
            "status": self.status.value,
            "created_at": self.created_at,
            "resolved_at": self.resolved_at,
            "user_response": self.user_response,
            "refined_query": self.refined_query
        }

