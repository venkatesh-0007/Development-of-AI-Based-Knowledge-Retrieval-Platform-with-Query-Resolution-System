@dataclass
class TransparencyScoreBreakdown:
    """Detailed formula breakdown for response confidence calculation (M3.4)."""
    top_chunk_score: float
    avg_top_k_score: float
    combined_score: float
    threshold: float
    confidence_level: ConfidenceLevel
    formula: str = "70% * Top-Chunk-Score + 30% * Avg-Top-K-Score"
    top_k_count: int = 0
    low_confidence_reasons: List[str] = field(default_factory=list)

    @property
    def combined_confidence(self) -> float:
        return self.combined_score

    @classmethod
    def from_chunks(
        cls,
        chunks: List[RetrievalChunk],
        threshold: float = 0.45
    ) -> "TransparencyScoreBreakdown":
        if not chunks:
            return cls(
                top_chunk_score=0.0,
                avg_top_k_score=0.0,
                combined_score=0.0,
                threshold=threshold,
                confidence_level=ConfidenceLevel.NONE,
                top_k_count=0,
                low_confidence_reasons=["No chunks retrieved from knowledge base."]
            )

        top_chunk_score = chunks[0].similarity_score if chunks[0].similarity_score is not None else 0.0
        scores = [c.similarity_score for c in chunks if c.similarity_score is not None]
        avg_score = sum(scores) / len(scores) if scores else 0.0
        combined = round(0.7 * top_chunk_score + 0.3 * avg_score, 4)

        if combined >= 0.70:
            level = ConfidenceLevel.HIGH
        elif combined >= 0.50:
            level = ConfidenceLevel.MEDIUM
        elif combined >= threshold:
            level = ConfidenceLevel.LOW
        else:
            level = ConfidenceLevel.NONE

        low_reasons = []
        if top_chunk_score < 0.50:
            low_reasons.append(f"Top chunk relevance is below 0.50 ({top_chunk_score:.2f}).")
        if combined < threshold:
            low_reasons.append(f"Combined score ({combined:.2f}) falls below threshold ({threshold:.2f}).")

        return cls(
            top_chunk_score=round(top_chunk_score, 4),
            avg_top_k_score=round(avg_score, 4),
            combined_score=combined,
            threshold=threshold,
            confidence_level=level,
            top_k_count=len(chunks),
            low_confidence_reasons=low_reasons
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "top_chunk_score": self.top_chunk_score,
            "avg_top_k_score": self.avg_top_k_score,
            "combined_score": self.combined_score,
            "threshold": self.threshold,
            "confidence_level": self.confidence_level.value,
            "formula": self.formula,
            "top_k_count": self.top_k_count,
            "low_confidence_reasons": self.low_confidence_reasons
        }

@dataclass
class TransparencyPanelPayload:
    """Structured transparency payload for deep evidence inspection (M3.4)."""
    retrieved_chunks: List[RetrievalChunk]
    citations: List[SourceAttribution]
    score_breakdown: TransparencyScoreBreakdown
    query: str = ""
    refined_query: Optional[str] = None
    confidence_level: ConfidenceLevel = ConfidenceLevel.MEDIUM
    confidence_score: float = 0.0
    source_documents: List[str] = field(default_factory=list)
    evidence_sufficient: bool = True
    low_confidence_reason: Optional[str] = None
    filtered_out_count: int = 0

    def __post_init__(self):
        if not self.confidence_score:
            self.confidence_score = self.score_breakdown.combined_score
        if not self.confidence_level:
            self.confidence_level = self.score_breakdown.confidence_level
        if not self.source_documents and self.citations:
            self.source_documents = list(dict.fromkeys(c.document_name for c in self.citations))

    def to_dict(self) -> Dict[str, Any]:
        return {
            "query": self.query,
            "refined_query": self.refined_query,
            "confidence_level": self.confidence_level.value,
            "confidence_score": self.confidence_score,
            "score_breakdown": self.score_breakdown.to_dict(),
            "source_documents": self.source_documents,
            "retrieved_chunks": [c.to_dict() for c in self.retrieved_chunks],
            "citations": [c.to_dict() for c in self.citations],
            "evidence_sufficient": self.evidence_sufficient,
            "low_confidence_reason": self.low_confidence_reason,
            "filtered_out_count": self.filtered_out_count
        }

