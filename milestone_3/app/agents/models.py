@dataclass
class ConversationTurn:
    """Represents a single multi-turn interaction in Conversation Memory (M3.2)."""
    user_query: str = ""
    contextualized_query: str = ""
    response: Any = None
    entities: List[str] = field(default_factory=list)
    referenced_docs: List[str] = field(default_factory=list)
    intent_type: QueryType = QueryType.FACTUAL
    turn_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    timestamp: float = field(default_factory=time.time)
    # Compatibility aliases
    query: Optional[str] = None
    effective_query: Optional[str] = None
    confidence_score: Optional[float] = None
    sources: Optional[List[Any]] = None
    key_entities: Optional[List[str]] = None
    transparency: Optional[Any] = None

    def __post_init__(self):
        if self.query and not self.user_query:
            self.user_query = self.query
        elif self.user_query and not self.query:
            self.query = self.user_query

        if self.effective_query and not self.contextualized_query:
            self.contextualized_query = self.effective_query
        elif self.contextualized_query and not self.effective_query:
            self.effective_query = self.contextualized_query

        if self.key_entities and not self.entities:
            self.entities = self.key_entities
        elif self.entities and not self.key_entities:
            self.key_entities = self.entities

    def to_dict(self) -> Dict[str, Any]:
        resp_dict = self.response.to_dict() if (self.response and hasattr(self.response, "to_dict")) else self.response
        return {
            "turn_id": self.turn_id,
            "user_query": self.user_query,
            "query": self.user_query,
            "contextualized_query": self.contextualized_query,
            "effective_query": self.contextualized_query,
            "response": resp_dict,
            "entities": self.entities,
            "referenced_docs": self.referenced_docs,
            "intent_type": self.intent_type.value if hasattr(self.intent_type, "value") else str(self.intent_type),
            "timestamp": self.timestamp
        }


@dataclass
class ConversationSession:
    """Manages active conversation session memory and turn history (M3.2)."""
    session_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    turns: List[ConversationTurn] = field(default_factory=list)
    active_clarification: Optional[ClarificationRequest] = None
    max_turns: int = 10
    created_at: float = field(default_factory=time.time)
    entity_history: List[str] = field(default_factory=list)
    primary_topic: Optional[str] = None

    def add_turn(self, turn: ConversationTurn) -> None:
        """Append turn, update entity history, and apply sliding window pruning."""
        self.turns.append(turn)
        for e in turn.entities:
            if e not in self.entity_history:
                self.entity_history.append(e)
        if turn.entities:
            self.primary_topic = turn.entities[0]
        # Prune oldest turns if exceeding max_turns
        if len(self.turns) > self.max_turns:
            self.turns = self.turns[-self.max_turns:]

    def get_last_turn(self) -> Optional[ConversationTurn]:
        """Return most recent conversation turn."""
        return self.turns[-1] if self.turns else None

    def get_recent_turns(self, k: int = 3) -> List[ConversationTurn]:
        """Return the most recent k turns."""
        return self.turns[-k:] if self.turns else []

    def clear(self) -> None:
        """Clear all session turn history and entity tracking."""
        self.turns.clear()
        self.entity_history.clear()
        self.primary_topic = None
        self.active_clarification = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "session_id": self.session_id,
            "turn_count": len(self.turns),
            "turns": [t.to_dict() for t in self.turns],
            "active_clarification": self.active_clarification.to_dict() if self.active_clarification else None,
            "entity_history": self.entity_history,
            "primary_topic": self.primary_topic,
            "created_at": self.created_at
        }

